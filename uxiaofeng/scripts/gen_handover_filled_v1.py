wb = openpyxl.Workbook()


def title_block(ws, title, ncols):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncols)
    c = ws.cell(row=1, column=1, value=title)
    c.font = Font(name="微软雅黑", size=14, bold=True, color="FFFFFF")
    c.fill = PatternFill("solid", fgColor=NAVY)
    c.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[1].height = 30
    ws.row_dimensions[2].height = 6


def build(name, title, headers, widths, data, validations=None, note=None):
    ws = wb.create_sheet(name)
    title_block(ws, title, len(headers))
    r0 = 3
    for i, (h, w) in enumerate(zip(headers, widths), start=1):
        c = ws.cell(row=r0, column=i, value=h)
        c.font = Font(name="微软雅黑", size=10, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=BLUE)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[r0].height = 32

    for ri, row in enumerate(data):
        r = r0 + 1 + ri
        ws.row_dimensions[r].height = 34
        for ci in range(1, len(headers) + 1):
            val = row[ci - 1] if ci - 1 < len(row) else None
            cell = ws.cell(row=r, column=ci, value=val)
            cell.font = Font(name="微软雅黑", size=10)
            align_h = "center" if ci in (1,) else "left"
            cell.alignment = Alignment(vertical="center", wrap_text=True, horizontal=align_h,
                                       indent=0 if ci == 1 else 1)
            cell.border = BORDER
            if ri % 2 == 1:
                cell.fill = PatternFill("solid", fgColor=GREY)
            if isinstance(val, str) and ("待填" in val or "待确认" in val):
                cell.fill = PatternFill("solid", fgColor=TBD)

    last = r0 + len(data)
    ws.freeze_panes = f"A{r0 + 1}"
    ws.auto_filter.ref = f"A{r0}:{get_column_letter(len(headers))}{last}"
    if validations:
        for col_idx, options in validations:
            dv = DataValidation(type="list", formula1='"' + ",".join(options) + '"', allow_blank=True)
            ws.add_data_validation(dv)
            L = get_column_letter(col_idx)
            dv.add(f"{L}{r0+1}:{L}{last}")
    if note:
        n = last + 2
        ws.merge_cells(start_row=n, start_column=1, end_row=n, end_column=len(headers))
        c = ws.cell(row=n, column=1, value=note)
        c.font = Font(name="微软雅黑", size=9, color="C00000")
        c.alignment = Alignment(vertical="center", wrap_text=True, indent=1)
    return ws


